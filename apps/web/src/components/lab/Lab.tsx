import { useState, type ComponentType } from 'react'
import { AnimatePresence, motion } from 'framer-motion'
import { ease } from '../../lib/motion'
import { Tags } from '../ui/Tags'
import { ModelGallery } from './ModelGallery'
import { ProjectShelf } from './shelf/ProjectShelf'
import { ScrollReveal } from './ScrollReveal'
import { SpringPhysics } from './SpringPhysics'

interface Demo {
  id: string
  name: string
  tech: string[]
  about: string
  Component: ComponentType
}

const DEMOS: Demo[] = [
  {
    id: 'shelf',
    name: 'Project shelf',
    tech: ['Drag to scroll', 'Shared layout animation', 'Scroll snap'],
    about:
      'Every project as a card standing on one long shelf. Drag it (it keeps gliding after you let go), swipe, or use the arrows. Hover lifts a card off the shelf and clicking grows it into its details.',
    Component: ProjectShelf,
  },
  {
    id: 'models',
    name: 'Model viewer',
    tech: ['Three.js', 'Orbit controls', 'Instanced meshes'],
    about:
      'Procedural models built in code: a voxel mascot that assembles itself, noise-based terrain and a maze generated by recursive backtracking.',
    Component: ModelGallery,
  },
  {
    id: 'scroll',
    name: 'Scroll-linked text',
    tech: ['useScroll', 'Motion values', 'No re-renders'],
    about:
      'Opacity and offset of every word are derived from scroll position through motion values, so the animation runs without re-rendering React.',
    Component: ScrollReveal,
  },
  {
    id: 'physics',
    name: 'Spring physics',
    tech: ['Gestures', 'Layout animation', 'Springs'],
    about: 'A reorderable list with layout animation, and a card you can fling that springs back inside its bounds based on release velocity.',
    Component: SpringPhysics,
  },
]

export function Lab() {
  const [active, setActive] = useState(DEMOS[0]!.id)
  const demo = DEMOS.find((d) => d.id === active)!
  return (
    <div className="lab">
      <div className="lab-tabs" role="tablist" aria-label="Experiments">
        {DEMOS.map((d, i) => (
          <button key={d.id} role="tab" aria-selected={active === d.id} className={active === d.id ? 'on' : ''} onClick={() => setActive(d.id)}>
            <span className="lab-no">{String(i + 1).padStart(2, '0')}</span>
            {d.name}
            {active === d.id && <motion.span layoutId="lab-underline" className="lab-underline" />}
          </button>
        ))}
      </div>
      <AnimatePresence mode="wait">
        <motion.div
          key={demo.id}
          className="lab-panel"
          initial={{ opacity: 0, y: 14 }}
          animate={{ opacity: 1, y: 0 }}
          exit={{ opacity: 0, y: -8 }}
          transition={{ duration: 0.35, ease }}
        >
          <div className="lab-info">
            <p>{demo.about}</p>
            <Tags items={demo.tech} />
          </div>
          <demo.Component />
        </motion.div>
      </AnimatePresence>
    </div>
  )
}
