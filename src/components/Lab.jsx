const PASSAGE = 'Good interfaces feel inevitable. Every animation here is tied to something you do, a scroll, a drag or a hover, so motion explains what changed instead of decorating it.'

function Word({ children, range, progress }) {
  const k = useTransform(progress, (p) => Math.min(Math.max((p - range[0]) / (range[1] - range[0]), 0), 1))
  const opacity = useTransform(k, (v) => 0.15 + v * 0.85)
  const y = useTransform(k, (v) => (1 - v) * 6)
  return <motion.span style={{ opacity, y }} className="scroll-word">{children} </motion.span>
}

// Words brighten in sequence as the box is scrolled: progress comes from the
// scroll container itself, not the page.
function ScrollReveal() {
  const box = useRef()
  const target = useRef()
  const { scrollYProgress } = useScroll({ container: box, target, offset: ['start end', 'end end'] })
  const words = PASSAGE.split(' ')
  const bar = useSpring(scrollYProgress, { stiffness: 200, damping: 30 })
  return (
    <div className="scroll-demo" ref={box}>
      <motion.div className="scroll-demo-bar" style={{ scaleX: bar }} />
      <p className="scroll-hint">Scroll inside this box ↓</p>
      <div className="scroll-spacer" />
      <p className="scroll-passage" ref={target}>
        {words.map((w, i) => (
          <Word key={i} progress={scrollYProgress} range={[i / words.length, (i + 1) / words.length]}>{w}</Word>
        ))}
      </p>
    </div>
  )
}

const TASKS = ['Prototype the movement', 'Model the level', 'Write the shaders', 'Playtest with friends', 'Ship it']

// Drag-to-reorder list plus a free-floating card that springs back with
// velocity-aware physics.
function SpringPhysics() {
  const [items, setItems] = useState(TASKS)
  const area = useRef()
  const x = useMotionValue(0)
  const rotate = useTransform(x, [-150, 150], [-12, 12])
  return (
    <div className="physics">
      <div>
        <p className="demo-label">Drag to reorder</p>
        <Reorder.Group axis="y" values={items} onReorder={setItems} className="reorder">
          {items.map((t, i) => (
            <Reorder.Item key={t} value={t} className="reorder-item" whileDrag={{ scale: 1.03, boxShadow: '0 12px 30px rgba(0,0,0,0.45)' }}>
              <span className="reorder-no">{String(i + 1).padStart(2, '0')}</span>
              {t}
              <span className="grip" aria-hidden="true">⋮⋮</span>
            </Reorder.Item>
          ))}
        </Reorder.Group>
      </div>
      <div>
        <p className="demo-label">Throw the card</p>
        <div className="throw-area" ref={area}>
          <motion.div
            className="throw-card"
            drag
            dragConstraints={area}
            dragElastic={0.25}
            dragTransition={{ bounceStiffness: 300, bounceDamping: 14 }}
            whileDrag={{ scale: 1.08, cursor: 'grabbing' }}
            style={{ x, rotate }}
          >
            <span>Purin</span>
            <small>drag me</small>
          </motion.div>
        </div>
      </div>
    </div>
  )
}

